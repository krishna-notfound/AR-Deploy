// Builds supabase/seed/sample_data.sql from the demo seed (src/services/mock/seed.ts), so the
// Supabase sample data and the demo mode stay identical. Usage: npm run db:sample-sql
//
// The SQL is idempotent: it deletes ONLY the four sample businesses (fixed UUIDs below; products,
// images, models, variants, analytics and memberships cascade) and inserts them again.
// Dates are relative to now(), so the file is stable and charts always show the last 30 days.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createJiti } from 'jiti'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const jiti = createJiti(import.meta.url, { alias: { '@': join(root, 'src') } })
const { createSeed } = await jiti.import(join(root, 'src/services/mock/seed.ts'))

// The public logo URL depends on the project; read it from .env.local (public value).
const env = Object.fromEntries(
  (() => {
    try {
      return readFileSync(join(root, '.env.local'), 'utf8')
    } catch {
      return ''
    }
  })()
    .split('\n')
    .filter((l) => /^\s*VITE_[A-Z_]+=/.test(l))
    .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
)
const SUPABASE_URL = process.env.VITE_SUPABASE_URL || env.VITE_SUPABASE_URL
if (!SUPABASE_URL) throw new Error('Set VITE_SUPABASE_URL (or create .env.local) to build logo URLs.')

const NOW = Date.UTC(2026, 0, 1) // fixed reference; converted to "days ago" below
const DAY = 86_400_000
const seed = createSeed(NOW)

/** Deterministic UUID for a demo id, so re-running replaces the same rows. */
export const sampleUuid = (id) => {
  const h = createHash('md5').update(`furnish-sample:${id}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const q = (v) => (v === undefined || v === null || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const ago = (iso) => `now() - interval '${Math.max(0, Math.round((NOW - Date.parse(iso)) / 3_600_000))} hours'`

const bizIds = seed.businesses.map((b) => sampleUuid(b.id))
const out = []
out.push(`-- GENERATED by scripts/sample-data/build-sql.mjs from src/services/mock/seed.ts. Do not edit by hand.
-- SAMPLE DATA for testing: 4 businesses (1 inactive), ${seed.products.length} products, 30 days of analytics.
-- Idempotent: removes and re-creates only the sample businesses below (everything else is untouched).
-- Apply in the Supabase SQL editor (or psql) as the postgres role. Then run scripts/sample-data/upload-logos.mjs.
begin;

delete from public.businesses where id in (${bizIds.map(q).join(', ')});
`)

for (const b of seed.businesses) {
  const id = sampleUuid(b.id)
  out.push(`insert into public.businesses (id, name, slug, logo_url, description, contact_email, contact_phone, contact_website, contact_address, status, accent_color, default_currency, created_at, updated_at)
values (${q(id)}, ${q(b.name)}, ${q(b.slug)}, ${q(`${SUPABASE_URL}/storage/v1/object/public/business-logos/${id}/logo.png`)}, ${q(`${b.description} (Sample business for testing.)`)}, ${q(b.contact.email)}, ${q(b.contact.phone)}, ${q(b.contact.website)}, ${q(b.contact.address)}, ${q(b.status)}, ${q(b.branding.accentColor)}, ${q(b.defaultCurrency)}, ${ago(b.createdAt)}, ${ago(b.updatedAt)});`)
}

for (const p of seed.products) {
  const id = sampleUuid(p.id)
  const biz = sampleUuid(p.businessId)
  out.push(`
insert into public.products (id, business_id, slug, name, short_description, description, material, cta_label, cta_url, category, price, currency, status, width, height, depth, dimension_unit, weight_value, weight_unit, published_at, created_at, updated_at)
values (${q(id)}, ${q(biz)}, ${q(p.slug)}, ${j(p.name)}, ${j(p.shortDescription)}, ${j(p.description)}, ${j(p.material)}, ${j(p.cta.label)}, ${q(p.cta.url)}, ${q(p.category)}, ${p.price}, ${q(p.currency)}, ${q(p.status)}, ${p.dimensions.width}, ${p.dimensions.height}, ${p.dimensions.depth}, ${q(p.dimensions.unit)}, ${p.weight ? p.weight.value : 'null'}, ${p.weight ? q(p.weight.unit) : 'null'}, ${p.publishedAt ? ago(p.publishedAt) : 'null'}, ${ago(p.createdAt)}, ${ago(p.updatedAt)});`)
  p.images.forEach((img, i) =>
    out.push(`insert into public.product_images (product_id, url, alt, is_primary, kind, sort_order) values (${q(id)}, ${q(img.url)}, ${q(img.alt)}, ${img.isPrimary}, ${q(img.kind)}, ${i});`),
  )
  for (const m of Object.values(p.models)) {
    if (m) out.push(`insert into public.product_models (product_id, format, url, file_name) values (${q(id)}, ${q(m.format)}, ${q(m.url)}, ${q(m.fileName)});`)
  }
  p.variants.forEach((v, i) =>
    out.push(`insert into public.product_variants (product_id, name, color_hex, sku, price_delta, sort_order) values (${q(id)}, ${j(v.name)}, ${q(v.colorHex)}, ${q(v.sku)}, ${v.priceDelta ?? 'null'}, ${i});`),
  )
}

// Analytics: generated in SQL, deterministic per product and day (hashtext), only for published products of
// active sample businesses. Shapes: 8–40 views/day (+10 with a 3D model), 10–25% AR taps for products with a
// model, ~35% 3D interactions. Timestamps spread over each day and never in the future.
out.push(`
-- Sample analytics: last 30 days of views, AR taps and 3D interactions (deterministic).
insert into public.product_analytics (product_id, business_id, event_type, created_at)
select p.id, p.business_id, t.event_type,
       least(now(), date_trunc('day', now()) - make_interval(days => d) + make_interval(secs => (g * 7919 % 86000)))
from public.products p
join public.businesses b on b.id = p.business_id and b.status = 'active'
cross join generate_series(0, 29) as d
cross join lateral (
  select exists (select 1 from public.product_models m where m.product_id = p.id) as has_model,
         abs(hashtext(p.id::text || ':' || d)) as h
) x
cross join lateral (select 8 + x.h % 33 + case when x.has_model then 10 else 0 end as views) v
cross join lateral (values
  ('view', v.views),
  ('ar_activation', case when x.has_model then v.views * (10 + x.h % 16) / 100 else 0 end),
  ('model_interaction', case when x.has_model then v.views * 35 / 100 else 0 end)
) as t(event_type, n)
cross join lateral generate_series(1, t.n) as g
where p.status = 'published' and p.business_id in (${bizIds.map(q).join(', ')});

`)
out.push(`-- Link sample owner accounts if they exist (create them in Authentication → Users first; no-op otherwise).
insert into public.business_members (business_id, user_id)
select ${q(sampleUuid('biz_casa'))}, id from auth.users where email = 'owner.casa@furnish.example'
on conflict do nothing;
insert into public.business_members (business_id, user_id)
select ${q(sampleUuid('biz_nord'))}, id from auth.users where email = 'owner.nordhaus@furnish.example'
on conflict do nothing;

commit;
`)

const file = join(root, 'supabase/seed/sample_data.sql')
mkdirSync(dirname(file), { recursive: true })
writeFileSync(file, out.join('\n'))
writeFileSync(
  join(root, 'supabase/seed/sample_logos.json'),
  JSON.stringify(seed.businesses.map((b) => ({ id: sampleUuid(b.id), name: b.name, svg: b.logoUrl })), null, 2) + '\n',
)
console.log(`wrote ${file} (${seed.businesses.length} businesses, ${seed.products.length} products)`)
